import os

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from dotenv import load_dotenv
from openai import OpenAI


# =========================================================
# ENVIRONMENT
# =========================================================

load_dotenv()

api_key = os.getenv("OPENAI_API_KEY")

if not api_key:
    raise RuntimeError(
        "OPENAI_API_KEY غير موجود في متغيرات البيئة."
    )


client = OpenAI(
    api_key=api_key
)


# =========================================================
# FASTAPI
# =========================================================

app = FastAPI(
    title="Rafiq AI Server",
    version="2.0"
)


# =========================================================
# CORS
# =========================================================

app.add_middleware(
    CORSMiddleware,

    allow_origins=["*"],

    allow_credentials=False,

    allow_methods=["*"],

    allow_headers=["*"],
)


# =========================================================
# REQUEST MODEL
# =========================================================

class DrawingRequest(BaseModel):

    image: str

    emotion: str


# =========================================================
# HOME
# =========================================================

@app.get("/")
def home():

    return {
        "status": "success",
        "message": "Rafiq AI server is running"
    }


# =========================================================
# HEALTH
# =========================================================

@app.get("/health")
def health():

    return {
        "status": "ok"
    }


# =========================================================
# ANALYZE DRAWING
# =========================================================

@app.post("/analyze-drawing")
def analyze_drawing(
    data: DrawingRequest
):

    try:

        print("🎨 Received drawing")

        print(
            "Emotion:",
            data.emotion
        )

        print(
            "Image received:",
            bool(data.image)
        )


        # =================================================
        # CHECK IMAGE
        # =================================================

        if not data.image:

            raise HTTPException(
                status_code=400,
                detail="لم يتم إرسال الرسم."
            )


        if "," not in data.image:

            raise HTTPException(
                status_code=400,
                detail="صيغة الصورة غير صحيحة."
            )


        # =================================================
        # ONLY SUPPORT HAPPINESS FOR NOW
        # =================================================

        emotion = data.emotion.strip()


        # =================================================
        # AI INSTRUCTIONS
        # =================================================

        prompt = f"""
أنت "رفيق"، مساعد تعليمي لطيف للأطفال.

الطفل طُلب منه رسم وجه يعبر عن:

{emotion}

مهمتك هي تقييم الرسم من ناحية تعليمية فقط.

لا تقيم جودة الرسم الفنية.
لا تنتقد الطفل.
لا تقل إن الرسم سيئ.
لا تقارن الرسم برسومات أخرى.
لا تحاول معرفة هوية الطفل.
لا تستنتج أي معلومات شخصية عن الطفل.

ركز بشكل أساسي على السؤال التالي:

هل رسم الطفل ابتسامة واضحة تدل على السعادة؟

==================================================
طريقة التقييم
==================================================

افحص الوجه المرسوم بعناية.

ركز على الفم أولًا.

اعتبر الفم "مبتسمًا" إذا كان هناك دليل بصري واضح
على أن زوايا الفم تتجه إلى الأعلى أو أن شكل الفم
يعطي تعبيرًا واضحًا عن الابتسامة.

أمثلة على الابتسامة:
- فم منحني للأعلى.
- قوس واضح يمثل ابتسامة.
- فم مفتوح بطريقة تبدو مبتسمة.
- زوايا الفم واضحة ومتجهة للأعلى.

لا تعتبر الوجه سعيدًا فقط لأنه يحتوي على:
- دائرة تمثل الوجه.
- عينين.
- ألوان جميلة.
- شعر.
- أنف.
- زخارف.
- قلب أو نجوم.
- أي عناصر أخرى لا تثبت وجود ابتسامة.

==================================================
حالات الفم
==================================================

اختر حالة واحدة فقط:

مبتسم
غير مبتسم
غير واضح
غير موجود

معنى الحالات:

"مبتسم":
توجد ابتسامة واضحة يمكن رؤيتها.

"غير مبتسم":
يوجد فم واضح لكنه مستقيم أو متجه للأسفل
أو لا يعطي تعبير السعادة المطلوب.

"غير واضح":
يوجد شيء يشبه الفم ولكن لا يمكن تحديد
هل هو مبتسم أم لا.

"غير موجود":
لا يوجد فم واضح في الرسم.

==================================================
MATCHES_TARGET
==================================================

اجعل:

matches_target: true

فقط إذا كانت هناك ابتسامة واضحة فعلًا.

إذا لم توجد ابتسامة واضحة:

matches_target: false

لا تجامل الطفل بجعلها true.

==================================================
CONFIDENCE
==================================================

أعطِ نسبة ثقة من 0 إلى 100.

النسبة تعبر عن مدى وضوح قرارك
من الرسم نفسه.

إذا كان الفم واضحًا جدًا:
يمكن أن تكون الثقة 85-100.

إذا كان الفم موجودًا لكن الرسم غير واضح:
استخدم 50-84.

إذا كان من الصعب معرفة التعبير:
استخدم أقل من 50.

لا تستخدم 100 إلا إذا كان الدليل البصري واضحًا جدًا.

==================================================
FEEDBACK
==================================================

اكتب ملاحظة قصيرة جدًا باللغة العربية.

يجب أن تكون لطيفة ومناسبة لطفل صغير.

إذا كانت الابتسامة واضحة:

مثال:
"أحسنت! أرى ابتسامة جميلة في وجهك."

إذا كان الفم غير مبتسم:

مثال:
"محاولة جميلة! جرّب أن تجعل زوايا الفم تتجه إلى الأعلى ليصبح الوجه سعيدًا."

إذا كان الفم غير واضح:

مثال:
"أحسنت! حاول رسم الفم بشكل أوضح واجعل الابتسامة تتجه إلى الأعلى."

إذا لم يوجد فم:

مثال:
"رائع! حاول إضافة فم مبتسم إلى الوجه."

إذا كان الرسم غير واضح بشكل عام:

مثال:
"محاولة جميلة! جرّب رسم وجه أوضح مع ابتسامة صغيرة."

لا تستخدم كلمات قاسية مثل:
خطأ
سيئ
فاشل
رسم غير جيد

==================================================
مهم جدًا
==================================================

أريد النتيجة بهذا الشكل بالضبط:

matches_target: true أو false
confidence: رقم من 0 إلى 100
mouth: مبتسم أو غير مبتسم أو غير واضح أو غير موجود
feedback: جملة عربية قصيرة

لا تضف شرحًا قبل هذه الأسطر.

لا تستخدم Markdown.

لا تضف JSON.

لا تضف رموزًا أو أسطرًا أخرى.

==================================================
الهدف
==================================================

الهدف ليس إعطاء الطفل درجة.

الهدف أن يتعلم الطفل تدريجيًا
كيف يستخدم شكل الفم للتعبير عن السعادة،
مع المحافظة على التشجيع واللطف.
"""


        # =================================================
        # SEND TO OPENAI
        # =================================================

        response = client.responses.create(

            model="gpt-5.6",

            input=[

                {
                    "role": "user",

                    "content": [

                        {
                            "type": "input_text",

                            "text": prompt
                        },

                        {
                            "type": "input_image",

                            "image_url": data.image
                        }

                    ]
                }

            ]

        )


        # =================================================
        # GET AI TEXT
        # =================================================

        ai_result = (
            response.output_text or ""
        ).strip()


        print(
            "🤖 AI RESULT:"
        )

        print(
            ai_result
        )


        # =================================================
        # FALLBACK
        # =================================================

        if not ai_result:

            ai_result = (
                "matches_target: false\n"
                "confidence: 0\n"
                "mouth: غير واضح\n"
                "feedback: محاولة جميلة! حاول رسم ابتسامة أوضح."
            )


        # =================================================
        # RETURN RESULT
        # =================================================

        return {

            "success": True,

            "ai_result": ai_result,

            "message": ai_result

        }


    # =====================================================
    # HTTP ERROR
    # =====================================================

    except HTTPException:

        raise


    # =====================================================
    # OPENAI / SERVER ERROR
    # =====================================================

    except Exception as e:

        print(
            "❌ AI ERROR:",
            str(e)
        )

        return {

            "success": False,

            "ai_result": "",

            "message":
                "لم نتمكن من تحليل الرسم الآن. "
                "حاولي مرة أخرى."

        }